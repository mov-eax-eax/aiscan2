// ── shared plumbing ────────────────────────────────────────────────────────

/** Clamp a quality value to 1-100. */
function clampQuality(quality) {
  if (!Number.isInteger(quality) || quality < 1 || quality > 100) throw new Error("quality must be an integer between 1 and 100");
  return quality;
}

/** Basename of a display path (mirrors node's basename on both separators). */
function basename(path) {
  const parts = String(path).split(/[\\/]/);
  return parts[parts.length - 1] || "image";
}

/**
 * Shared tail for transform tools: write the output file when requested, then
 * commit a downscaled preview of the result to the attachment store and
 * return the model-facing outcome.
 */
async function commitResult(ctx, exec, inputTarget, buffer, format, config, outputPath) {
  let written;
  if (outputPath !== undefined) {
    written = await writeOutputFile(ctx, exec, outputPath, buffer);
    if (exec.signal.aborted) throw new Error("tool aborted while writing output");
  }
  const mediaType = FORMAT_MEDIA_TYPES[format];
  const preview = await sharp(buffer).rotate().resize({
    width: config.previewMaxSize,
    height: config.previewMaxSize,
    fit: "inside",
    withoutEnlargement: true
  }).toBuffer();
  const ref = await saveAttachmentBounded(ctx, preview, mediaType, `${basename(inputTarget.displayPath)}.${format}`);
  const extraLines = written === undefined ? [] : [`Wrote ${written.target.displayPath} (${buffer.byteLength} bytes)`];
  return buildImageOutcome(ctx, exec, inputTarget.displayPath, ref, `${basename(inputTarget.displayPath)}.${format}`, extraLines, written?.target.displayPath);
}

/** Cordis plugin entry: register the read-only tool always, image-block tools while a durable attachment store is mounted. */
export function apply(ctx, config) {
  const resolved = config;
  if (!Number.isInteger(resolved.maxInputBytes) || resolved.maxInputBytes < 1) throw new Error("image-tools: maxInputBytes must be a positive integer");
  if (!Number.isInteger(resolved.previewMaxSize) || resolved.previewMaxSize < 1) throw new Error("image-tools: previewMaxSize must be a positive integer");
  if (!Number.isInteger(resolved.previewQuality) || resolved.previewQuality < 1 || resolved.previewQuality > 100) throw new Error("image-tools: previewQuality must be between 1 and 100");
  if (!Number.isInteger(resolved.defaultQuality) || resolved.defaultQuality < 1 || resolved.defaultQuality > 100) throw new Error("image-tools: defaultQuality must be between 1 and 100");
  registerImageInfoTool(ctx, resolved);
  ctx.inject(["attachments"], (imageCtx) => {
    registerImagePreviewTool(imageCtx, resolved);
    registerImageResizeTool(imageCtx, resolved);
    registerImageConvertTool(imageCtx, resolved);
    registerImageCropTool(imageCtx, resolved);
    registerImageRotateTool(imageCtx, resolved);
  });
}
