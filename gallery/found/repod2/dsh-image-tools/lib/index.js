// dsh-image-tools — server half.
//
// A cordis plugin that registers image viewing and processing tools into the
// harness tool registry:
//
//   image_info     — read-only metadata (format, dimensions, space, …)
//   image_preview  — bounded thumbnail committed to the attachment store,
//                    returned as a native image block (the "see it" tool)
//   image_resize   — resize to width/height/fit, optional output file
//   image_convert  — convert format/quality, optional output file
//   image_crop     — crop by region or gravity, optional output file
//   image_rotate   — rotate/flip/flop, optional output file
//
// Every transform (and preview) returns the processed image as a durable
// native image block — the same mechanism `read_image` uses — so the routed
// model sees the result and the web UI renders it inline.
//
// Processing is done with sharp; input bytes come through the bounded
// `ctx.fs` seam, output files are written through `ctx.fs.processPath` (the
// provider's execution-world path), and the displayed image is committed
// through `ctx.attachments.saveImage` (content-addressed, validated).
//
// Contract mirrors @deepseek-ai/dsh-tool-fs: plain cordis plugin exporting
// `name`, `inject`, `Config`, `apply`.

import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import z from "@deepseek-ai/schemastery";
import { defineTool } from "@deepseek-ai/dsh-tools";
import { AttachmentId } from "@deepseek-ai/dsh-attachment";
import { createUserMessage } from "@deepseek-ai/dsh-llm";

/** Cordis plugin name used by loader diagnostics. */
export const name = "image-tools";
/** Services required by the image tool suite. */
export const inject = ["tools", "fs"];

const MB = 1024 * 1024;

/** Plugin configuration (all optional; defaults are the shipped caps). */
export const Config = z.object({
  /** Byte cap on reading one input image (whole file must fit in memory for sharp). */
  maxInputBytes: z.number().default(64 * MB),
  /** Largest edge (px) of the attachment-committed preview/image block. */
  previewMaxSize: z.number().default(512),
  /** Format used for previews and for transforms whose input format is not previewable. */
  previewFormat: z.enum(["webp", "jpeg", "png"]).default("webp"),
  /** Quality for lossy preview encodes (1-100). */
  previewQuality: z.number().default(72),
  /** Default quality for lossy output encodes when the model omits `quality`. */
  defaultQuality: z.number().default(85)
});

/** Output formats the attachment store accepts for image blocks. */
const REQUESTED_FORMATS = ["png", "jpeg", "webp", "gif"];
/** Map an output format name to its media type. */
const FORMAT_MEDIA_TYPES = {
  png: "image/png",
  jpeg: "image/jpeg",
  webp: "image/webp",
  gif: "image/gif"
};
/** Map a media type back to its sharp format name (for re-encoding). */
const MEDIA_TYPE_FORMATS = Object.fromEntries(Object.entries(FORMAT_MEDIA_TYPES).map(([format, media]) => [media, format]));
/** sharp `position` strings accept both spellings; normalize to sharp's `centre`. */
function normalizeGravity(gravity) {
  return gravity === "center" ? "centre" : gravity;
}

/** The session workspace cwd for this call, or undefined for non-agent callers. */
function sessionCwd(exec) {
  return exec.agent?.session?.header?.cwd;
}

/** Resolve a model-supplied path with the session cwd and cancellation. */
function resolveOptions(exec) {
  const cwd = sessionCwd(exec);
  return {
    ...cwd !== undefined ? { cwd } : {},
    signal: exec.signal
  };
}

/**
 * Resolve an input path, require a regular file, and read it within the
 * configured byte cap through the bounded `ctx.fs` seam.
 */
async function resolveInput(ctx, exec, requestedPath, maxInputBytes) {
  if (typeof requestedPath !== "string" || requestedPath.trim().length === 0) throw new Error("path must be a non-empty string");
  const target = await ctx.fs.resolve(requestedPath, resolveOptions(exec));
  const info = await ctx.fs.stat(target, exec.signal);
  if (info === undefined) throw new Error(`cannot read "${target.displayPath}": not found`);
  if (info.type !== "file") throw new Error(`cannot read "${target.displayPath}": not a regular file`);
  const data = await ctx.fs.readBytes(target, exec.signal, maxInputBytes);
  return { target, data };
}

/**
 * Write generated bytes to an output path through the provider's execution
 * world (the sandbox confines the write like every other mutation).
 */
async function writeOutputFile(ctx, exec, outputPath, data) {
  if (typeof outputPath !== "string" || outputPath.trim().length === 0) throw new Error("output_path must be a non-empty string");
  const target = await ctx.fs.resolve(outputPath, resolveOptions(exec));
  const absolute = ctx.fs.processPath(target);
  await writeFile(absolute, data, { signal: exec.signal });
  return { target, absolute };
}

/**
 * Enforce the strict image-capability gate for the calling route: emitting a
 * durable image block on a route that cannot carry it would break that
 * route's continuation, so unknown capability refuses.
 */
async function assertImageCapableRoute(ctx, exec, requestedPath) {
  const routed = exec.agent?.session?.requestHeader?.()?.config;
  const provider = routed?.provider ?? exec.agent?.options.provider;
  const model = routed?.model ?? exec.agent?.options.model;
  const llm = ctx.get("llm");
  if (provider === undefined || model === undefined || llm === undefined) throw new Error(`cannot read "${requestedPath}" as an image: the current model route could not be resolved`);
  const active = await llm.resolveModelInfo(provider, model, exec.signal);
  if (active.inputModalities === undefined || !active.inputModalities.includes("image")) throw new Error(`cannot read "${requestedPath}" as an image: model "${model}" does not declare image input; switch to an image-capable model to read images`);
}

/**
 * Commit image bytes to the attachment store, downscaling first whenever the
 * buffer exceeds the deployment's byte or pixel limits so a tool call never
 * fails just because the output is large.
 */
async function saveAttachmentBounded(ctx, data, mediaType, name) {
  const attachments = ctx.get("attachments");
  if (attachments === undefined) throw new Error("no attachment service is mounted");
  const limits = attachments.imageLimits;
  if (!limits.mediaTypes.includes(mediaType)) throw new Error(`${mediaType} images are not accepted by this deployment (accepted: ${limits.mediaTypes.join(", ")})`);
  let candidate = data;
  const meta = await sharp(data).metadata();
  const pixels = (meta.width ?? 0) * (meta.height ?? 0);
  if (pixels > limits.maxImagePixels || candidate.byteLength > limits.maxImageBytes) {
    const pixelScale = Math.sqrt(limits.maxImagePixels / Math.max(1, pixels));
    const byteScale = Math.min(1, (limits.maxImageBytes * 0.92) / candidate.byteLength);
    const scale = Math.max(0.01, Math.min(pixelScale, byteScale));
    const format = MEDIA_TYPE_FORMATS[mediaType] ?? "jpeg";
    let pipeline = sharp(data).rotate().resize({
      width: Math.max(1, Math.round((meta.width ?? 0) * scale)),
      height: Math.max(1, Math.round((meta.height ?? 0) * scale)),
      fit: "inside",
      withoutEnlargement: true
    });
    if (format === "jpeg") candidate = await pipeline.jpeg({ quality: 78 }).toBuffer();
    else if (format === "webp") candidate = await pipeline.webp({ quality: 78 }).toBuffer();
    else if (format === "png") candidate = await pipeline.png().toBuffer();
    else candidate = await pipeline.gif().toBuffer();
  }
  const ref = await attachments.saveImage({ data: candidate, mediaType, name });
  return ref;
}

/** Encode a sharp pipeline's buffer in the requested format with a quality. */
async function encodeBuffer(pipeline, format, quality) {
  switch (format) {
    case "jpeg": return pipeline.jpeg({ quality }).toBuffer();
    case "webp": return pipeline.webp({ quality }).toBuffer();
    case "png": return pipeline.png().toBuffer();
    case "gif": return pipeline.gif().toBuffer();
    default: throw new Error(`unsupported output format: ${format}`);
  }
}

/** Pick the output format: the model's request, else the input format when previewable, else the configured preview format. */
function resolveOutputFormat(requested, inputFormat, config) {
  if (requested !== undefined) return requested;
  if (REQUESTED_FORMATS.includes(inputFormat)) return inputFormat;
  return config.previewFormat;
}

/** Model-facing envelope beside the native image block, mirroring `read_image`. */
function imageToolContent(value, extraLines = []) {
  const image = value.image;
  const lines = [`${image.mediaType} image, ${image.width}x${image.height} px, ${image.bytes} bytes`, ...extraLines];
  return [{
    type: "text",
    text: `<path>${value.path}</path>\n<type>image</type>\n<content>\n${lines.join("\n")}\n</content>`
  }, {
    type: "image",
    attachment: {
      attachmentId: AttachmentId(image.attachmentId),
      mediaType: image.mediaType,
      bytes: image.bytes,
      width: image.width,
      height: image.height,
      ...image.name === undefined ? {} : { name: image.name }
    }
  }];
}

/** Shared output schema for every tool that returns a native image block. */
const imageOutcomeSchema = {
  type: "object",
  additionalProperties: false,
  properties: {
    path: { type: "string", required: true },
    outputPath: { type: "string" },
    image: {
      type: "object",
      additionalProperties: false,
      required: true,
      properties: {
        attachmentId: { type: "string", required: true },
        mediaType: { type: "string", enum: ["image/png", "image/jpeg", "image/webp", "image/gif"], required: true },
        bytes: { type: "integer", required: true },
        width: { type: "integer", required: true },
        height: { type: "integer", required: true },
        name: { type: "string" }
      }
    }
  }
};

/** Shape one processed-image outcome and defer it for nested dispatches. */
function buildImageOutcome(ctx, exec, displayPath, ref, name, extraLines = [], outputPath) {
  const value = {
    path: displayPath,
    ...outputPath === undefined ? {} : { outputPath },
    image: {
      attachmentId: ref.attachmentId,
      mediaType: ref.mediaType,
      bytes: ref.bytes,
      width: ref.width,
      height: ref.height,
      ...ref.name === undefined && name === undefined ? {} : { name: ref.name ?? name }
    }
  };
  if (exec.parent !== undefined) exec.deferContext(createUserMessage({
    content: imageToolContent(value, extraLines),
    source: { kind: "plugin", plugin: "image-tools" }
  }));
  return value;
}

