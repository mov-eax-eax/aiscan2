/** Register the `image_crop` tool. */
function registerImageCropTool(ctx, config) {
  ctx.tools.register(defineTool({
    name: "image_crop",
    description: "Crop an image. Give width/height plus a gravity (default center) for a centered/anchored crop, or give left/top/width/height for an exact pixel region (extract). Writes the full-size result to output_path when given, and always returns a downscaled preview as a native image block.",
    parameters: {
      path: { type: "string", required: true, description: "Path to the source image, resolved by the filesystem backend." },
      width: { type: "integer", description: "Crop width in pixels (required for a gravity crop)." },
      height: { type: "integer", description: "Crop height in pixels (required for a gravity crop)." },
      gravity: { type: "string", enum: ["north", "centre", "center", "south", "east", "west", "north east", "north west", "south east", "south west", "center"], description: "Anchor for a gravity crop; default center." },
      left: { type: "integer", description: "Left edge for an exact region extract." },
      top: { type: "integer", description: "Top edge for an exact region extract." },
      format: { type: "string", enum: ["png", "jpeg", "webp", "gif"], description: "Output format; default keeps the input format when previewable, else webp." },
      quality: { type: "integer", description: "Lossy encode quality 1-100; default 85." },
      output_path: { type: "string", description: "Write the full-size result to this path (sandbox-contained)." }
    },
    output: { schema: imageOutcomeSchema, render: (args, value) => imageToolContent(value) },
    timeoutMs: 60000,
    async execute(args, exec) {
      await assertImageCapableRoute(ctx, exec, args.path);
      const { target, data } = await resolveInput(ctx, exec, args.path, config.maxInputBytes);
      if (args.quality !== undefined && !Number.isInteger(args.quality)) throw new Error("quality must be an integer");
      const exactRegion = args.left !== undefined || args.top !== undefined;
      let pipeline = sharp(data).rotate();
      if (exactRegion) {
        const left = args.left ?? 0;
        const top = args.top ?? 0;
        const width = args.width;
        const height = args.height;
        if (width === undefined || height === undefined || !Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) throw new Error("left/top crops require integer width and height");
        if (!Number.isInteger(left) || left < 0 || !Number.isInteger(top) || top < 0) throw new Error("left and top must be non-negative integers");
        pipeline = pipeline.extract({ left, top, width, height });
      } else {
        const width = args.width;
        const height = args.height;
        if (width === undefined || height === undefined || !Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) throw new Error("width and height are required for a gravity crop");
        pipeline = pipeline.resize({ width, height, fit: "cover", position: normalizeGravity(args.gravity ?? "centre"), withoutEnlargement: false });
      }
      const format = resolveOutputFormat(args.format, (await sharp(data).metadata()).format, config);
      const quality = clampQuality(args.quality ?? config.defaultQuality);
      const buffer = await encodeBuffer(pipeline, format, quality);
      if (exec.signal.aborted) throw new Error("image_crop aborted");
      return await commitResult(ctx, exec, target, buffer, format, config, args.output_path);
    },
    presentCall(args) {
      return { card: "generic", title: `Crop ${args.path}`, kind: "image", locations: [{ path: args.path }] };
    }
  }));
}

