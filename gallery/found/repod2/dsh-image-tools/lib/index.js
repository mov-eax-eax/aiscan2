/** Register the `image_resize` tool. */
function registerImageResizeTool(ctx, config) {
  ctx.tools.register(defineTool({
    name: "image_resize",
    description: "Resize an image to the requested width/height with a fit mode (cover, contain, fill, inside, outside). Writes the full-size result to output_path when given, and always returns a downscaled preview of the result as a native image block. width and height are optional but at least one is required.",
    parameters: {
      path: { type: "string", required: true, description: "Path to the source image, resolved by the filesystem backend." },
      width: { type: "integer", description: "Target width in pixels." },
      height: { type: "integer", description: "Target height in pixels." },
      fit: { type: "string", enum: ["cover", "contain", "fill", "inside", "outside"], description: "How the image fits the box; default contain." },
      format: { type: "string", enum: ["png", "jpeg", "webp", "gif"], description: "Output format; default keeps the input format when previewable, else webp." },
      quality: { type: "integer", description: "Lossy encode quality 1-100; default 85." },
      output_path: { type: "string", description: "Write the full-size result to this path (sandbox-contained)." }
    },
    output: { schema: imageOutcomeSchema, render: (args, value) => imageToolContent(value) },
    timeoutMs: 60000,
    async execute(args, exec) {
      await assertImageCapableRoute(ctx, exec, args.path);
      const { target, data } = await resolveInput(ctx, exec, args.path, config.maxInputBytes);
      if (args.width !== undefined && (!Number.isInteger(args.width) || args.width < 1)) throw new Error("width must be a positive integer");
      if (args.height !== undefined && (!Number.isInteger(args.height) || args.height < 1)) throw new Error("height must be a positive integer");
      if (args.width === undefined && args.height === undefined) throw new Error("at least one of width or height is required");
      if (args.quality !== undefined && !Number.isInteger(args.quality)) throw new Error("quality must be an integer");
      const format = resolveOutputFormat(args.format, (await sharp(data).metadata()).format, config);
      const quality = clampQuality(args.quality ?? config.defaultQuality);
      const buffer = await encodeBuffer(
        sharp(data).rotate().resize({ width: args.width, height: args.height, fit: args.fit ?? "contain", withoutEnlargement: false }),
        format,
        quality
      );
      if (exec.signal.aborted) throw new Error("image_resize aborted");
      return await commitResult(ctx, exec, target, buffer, format, config, args.output_path);
    },
    presentCall(args) {
      const dims = `${args.width ?? "auto"}x${args.height ?? "auto"} ${args.fit ?? "contain"}`;
      return { card: "generic", title: `Resize ${args.path} → ${dims}`, kind: "image", locations: [{ path: args.path }] };
    }
  }));
}

