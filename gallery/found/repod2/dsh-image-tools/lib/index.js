/** Register the read-only `image_info` metadata tool. */
function registerImageInfoTool(ctx, config) {
  ctx.tools.register(defineTool({
    name: "image_info",
    description: "Inspect an image file's metadata: format, dimensions, color space, channels, density, page count, and byte size. Read-only; does not display the image — use image_preview or read_image to see it.",
    parameters: {
      path: { type: "string", required: true, description: "Path to the image file, resolved by the filesystem backend." }
    },
    output: {
      schema: {
        type: "object",
        additionalProperties: false,
        properties: {
          path: { type: "string", required: true },
          info: {
            type: "object",
            additionalProperties: false,
            required: true,
            properties: {
              format: { type: "string", required: true },
              width: { type: "integer", required: true },
              height: { type: "integer", required: true },
              channels: { type: "integer", required: true },
              space: { type: "string", required: true },
              size: { type: "integer", required: true },
              density: { type: "integer" },
              pages: { type: "integer" },
              hasAlpha: { type: "boolean", required: true },
              orientation: { type: "integer" }
            }
          }
        }
      },
      render: (_args, value) => [{
        type: "text",
        text: [
          `<path>${value.path}</path>`,
          "<type>file</type>",
          "<content>",
          `format: ${value.info.format}`,
          `size: ${value.info.width}x${value.info.height} px`,
          `channels: ${value.info.channels}, space: ${value.info.space}`,
          `bytes: ${value.info.size}`,
          ...value.info.density === undefined ? [] : [`density: ${value.info.density}`],
          ...value.info.pages === undefined ? [] : [`pages: ${value.info.pages}`],
          `alpha: ${value.info.hasAlpha}`,
          ...value.info.orientation === undefined ? [] : [`orientation: ${value.info.orientation}`],
          "</content>"
        ].join("\n")
      }]
    },
    isConcurrencySafe: () => true,
    timeoutMs: 30000,
    async execute(args, exec) {
      const { target, data } = await resolveInput(ctx, exec, args.path, config.maxInputBytes);
      const meta = await sharp(data).metadata();
      const info = {
        format: meta.format ?? "unknown",
        width: meta.width ?? 0,
        height: meta.height ?? 0,
        channels: meta.channels ?? 0,
        space: meta.space ?? "unknown",
        size: data.byteLength,
        ...meta.density === undefined ? {} : { density: Math.round(meta.density) },
        ...meta.pages === undefined ? {} : { pages: meta.pages },
        hasAlpha: meta.hasAlpha ?? false,
        ...meta.orientation === undefined ? {} : { orientation: meta.orientation }
      };
      return { path: target.displayPath, info };
    },
    presentCall(args) {
      return { card: "generic", title: `Image info ${args.path}`, kind: "info", locations: [{ path: args.path }] };
    }
  }));
}

// ── image_preview ──────────────────────────────────────────────────────────

/** Register the `image_preview` tool: a bounded thumbnail as a native image block. */
function registerImagePreviewTool(ctx, config) {
  ctx.tools.register(defineTool({
    name: "image_preview",
    description: "Show an image in the conversation: decode it, auto-orient, scale it down to fit within max_size pixels (no upscaling), and return the result as a native image block. The model and the web UI both see the preview. To inspect metadata instead, use image_info.",
    parameters: {
      path: { type: "string", required: true, description: "Path to the image file, resolved by the filesystem backend." },
      max_size: { type: "integer", description: "Largest edge in pixels; default 512." },
      format: { type: "string", enum: ["webp", "jpeg", "png"], description: "Preview format; default webp." },
      quality: { type: "integer", description: "Lossy encode quality 1-100; default 72." }
    },
    output: { schema: imageOutcomeSchema, render: (args, value) => imageToolContent(value) },
    isConcurrencySafe: () => true,
    timeoutMs: 60000,
    async execute(args, exec) {
      await assertImageCapableRoute(ctx, exec, args.path);
      const { target, data } = await resolveInput(ctx, exec, args.path, config.maxInputBytes);
      const maxSize = args.max_size === undefined ? config.previewMaxSize : args.max_size;
      if (!Number.isInteger(maxSize) || maxSize < 1) throw new Error("max_size must be a positive integer");
      if (maxSize > 4096) throw new Error("max_size must be at most 4096");
      const format = args.format ?? config.previewFormat;
      const quality = clampQuality(args.quality ?? config.previewQuality);
      const buffer = await encodeBuffer(
        sharp(data).rotate().resize({ width: maxSize, height: maxSize, fit: "inside", withoutEnlargement: true }),
        format,
        quality
      );
      if (exec.signal.aborted) throw new Error("image_preview aborted");
      const ref = await saveAttachmentBounded(ctx, buffer, FORMAT_MEDIA_TYPES[format], `${basename(target.displayPath)}.preview.${format}`);
      return buildImageOutcome(ctx, exec, target.displayPath, ref, `${basename(target.displayPath)}.preview.${format}`);
    },
    presentCall(args) {
      return { card: "generic", title: `Preview ${args.path}`, kind: "image", locations: [{ path: args.path }] };
    }
  }));
}

