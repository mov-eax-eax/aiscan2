import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const onto = JSON.parse(readFileSync(join(root, "ontology", "compound-bow.ontology.json"), "utf8"));
const TICK = String.fromCharCode(96);
const c = (s) => TICK + s + TICK;
const L = [];
const push = (...xs) => L.push(...xs);
const esc = (s) => String(s).replace(/[|]/g, "/");

push("# Compound bow ontology", "");
push("A formal description of a modern compound bow: what its parts are, how they connect, and the");
push("cam-and-cable mechanics that make it compound. It is written to drive a parametric 3D model");
push("- **geometry is authored from this data, physics is a readout** - and it is checked by");
push(c("tools/validate.mjs") + ".", "");
push("This file is generated by reading " + c("ontology/compound-bow.ontology.json") + ". Edit the JSON, then");
push("regenerate with " + c("node tools/render-ontology.mjs") + "; do not hand-edit this document.", "");

push("## 1. Why an ontology first", "");
push("A compound bow is not one mechanism; it is five that only make sense together: a rigid riser,");
push("elastic limbs, non-circular eccentrics, a cable train and the accessory stack. Getting the");
push("*names* and *interfaces* right before modelling anything means the model can be assembled,");
push("exploded, measured and verified part by part, and means the physics has an unambiguous object");
push("to attach to. The ontology separates four things that are easy to confuse: the **class** of a");
push("part, the **individual** fitted to this bow, the **material** it is made from, and the");
push("**relations** that hold between parts.", "");

push("## 2. The reference bow", "");
push("The measured target is the **" + onto.meta.reference.model + "** - " + onto.meta.reference.rationale, "");
push("| specification | value |", "|---|---|");
push("| Axle-to-axle | " + onto.meta.reference.publishedSpecs.axleToAxle_in + " in |");
push("| Brace height | " + onto.meta.reference.publishedSpecs.braceHeight_in + " in |");
push("| Draw length | " + onto.meta.reference.publishedSpecs.drawLengthRange_in.join("-") + " in |");
push("| Peak draw weight | " + onto.meta.reference.publishedSpecs.peakDrawWeight_lb.join("-") + " lb |");
push("| Let-off | " + onto.meta.reference.publishedSpecs.letOff_pct.join(" / ") + " % |");
push("| IBO speed | " + onto.meta.reference.publishedSpecs.iboSpeed_fps + " fps |");
push("| Mass weight | " + onto.meta.reference.publishedSpecs.massWeight_lb + " lb |", "");
push("Every number carries a provenance label (published, standard, classTypical, derived) in");
push(c("refs/dimensions.json") + ", together with a confidence and, for class-typical rows, a plausible band.", "");

push("## 3. Class tree (" + onto.classes.length + " classes)", "");
const byParent = {};
for (const cl of onto.classes) { const k = cl.parent == null ? "__root" : cl.parent; (byParent[k] = byParent[k] || []).push(cl); }
for (const k of Object.keys(byParent)) byParent[k].sort((a, b) => a.id.localeCompare(b.id));
function walk(id, depth) {
  for (const cl of (byParent[id] || [])) {
    let tags = cl.abstract ? "abstract" : "";
    if (cl.typicalMaterials) tags += (tags ? "; " : "") + "materials: " + cl.typicalMaterials.join(", ");
    push("  ".repeat(depth) + "* **" + cl.label + "** (" + c(cl.id) + ")" + (tags ? " - " + tags : ""));
    walk(cl.id, depth + 1);
  }
}
walk("__root", 0);
push("");

push("## 4. Relations (" + onto.objectProperties.length + " object properties)", "", "| relation | domain | range | definition |", "|---|---|---|---|");
for (const op of onto.objectProperties) push("| " + c(op.id) + " | " + op.domain + " | " + op.range + " | " + esc(op.definition || "") + " |");
push("", "Datatype properties (measurable attributes): " + onto.datatypeProperties.map((d) => c(d.id) + " (" + d.unit + ")").join(", ") + ".", "");

push("## 5. Materials (" + onto.materials.length + ")", "", "| id | material | used for |", "|---|---|---|");
for (const m of onto.materials) push("| " + c(m.id) + " | " + esc(m.label) + " | " + esc(m.use || "") + " |");
push("");

const byId = {};
for (const i of onto.individuals) byId[i.id] = i;
push("## 6. The parts (" + onto.individuals.length + " individuals, grouped by subsystem)", "");
for (const s of onto.subsystems) {
  push("### " + s.label, "", "*" + s.function + "*", "", "| part | class | material | qty |", "|---|---|---|---|");
  for (const pid of s.parts) {
    const i = byId[pid];
    const mat = i.material ? c(i.material) : "-";
    push("| **" + i.label + "** (" + c(i.id) + ") | " + i.class + " | " + mat + " | " + (i.qty == null ? 1 : i.qty) + " |");
  }
  push("");
}

const mech = onto.mechanics;
push("## 7. Mechanics", "", mech.summary, "", "### 7.1 Eccentric topologies", "", "| topology | cams | idlers | cables | definition |", "|---|---|---|---|---|");
for (const t of mech.eccentricTopologies) push("| **" + t.label + "** (" + c(t.id) + ") | " + (t.cams == null ? "-" : t.cams) + " | " + (t.idlers == null ? "-" : t.idlers) + " | " + (t.cables == null ? "-" : t.cables) + " | " + esc(t.definition) + " |");
push("", "### 7.2 The reference cam system", "", "**" + mech.referenceEccentricSystem.label + "** (topology: " + c(mech.referenceEccentricSystem.topology) + ").", "");
for (const pr of mech.referenceEccentricSystem.principle) push("* " + pr);
push("", "### 7.3 Draw cycle (" + mech.drawCycle.totalCamRotation_deg + " degrees of cam rotation)", "", "*" + mech.drawCycle.note + "*", "", "| phase | draw | cam rotation | force | behaviour |", "|---|---|---|---|---|");
for (const ph of mech.drawCycle.phases) {
  const d = Array.isArray(ph.draw_in) ? ph.draw_in.join("-") : ph.draw_in;
  const cr = Array.isArray(ph.camRotation_deg) ? ph.camRotation_deg.join("-") : ph.camRotation_deg;
  push("| **" + ph.id + "** | " + d + " | " + cr + " | " + esc(ph.force) + " | " + esc(ph.behaviour) + " |");
}
push("", "### 7.4 Let-off and energy", "", c(mech.letOff.definition), "", "| peak (lb) | let-off (%) | holding (lb) |", "|---|---|---|");
for (const e of mech.letOff.examples) push("| " + e.peak_lb + " | " + e.letOff_pct + " | " + e.holding_lb + " |");
push("");
push("* Stored energy: " + c(mech.energy.storedEnergy.formula) + " - the area under the force-draw curve.");
push("* Arrow energy: " + c(mech.energy.arrowKinetic.formula) + ".");
push("* Efficiency: " + mech.energy.efficiency.typical_pct.join("-") + " percent.");
push("* IBO sanity check: " + mech.energy.iboCheck.arrow_gr + " gr at " + mech.energy.iboCheck.speed_fps + " fps gives " + mech.energy.iboCheck.ke_ftLb + " ft-lb, implying " + mech.energy.iboCheck.impliedStoredAt80pct_ftLb + " ft-lb stored at 80 percent efficiency - a stored/peak ratio of " + mech.energy.iboCheck.impliedStoredToPeakRatio + ", **above** the 1.0-1.4 class band, so the IBO speed must not be read as a guaranteed delivered speed.");
push("", "### 7.5 Synchronisation", "", mech.synchronisation.definition, "");
push("* Mechanisms: " + mech.synchronisation.mechanisms.join("; ") + ".");
push("* Observable: " + mech.synchronisation.observable + ".", "");

push("## 8. Operating states", "");
for (const s of onto.states) push("* **" + s.label + "** - " + s.description);
push("", "## 9. Build order", "", "The assembly order the eventual model should explode along.", "");
for (const b of onto.buildPhases) push(b.order + ". **" + b.label + "** - " + b.note + " (" + b.parts.length + " parts)");
push("", "## 10. Validating and extending", "");
push("    node tools/validate.mjs", "");
push("Checks referential integrity (every parent, class, material and part reference resolves), that");
push("the class tree is acyclic, that every part is grouped into a subsystem and a build phase, the");
push("mechanics consistency, and - most usefully - that every derived dimension recomputes from its");
push("own formula.", "");
push("To extend: add a class, then an individual of it, then place that individual in a subsystem and");
push("a build phase, and re-run the validator. It reports what is missing.", "");
push("## 11. Sources", "");
for (const s of onto.sources) push("* [" + s.title + "](" + s.url + ") - " + s.publisher + " (" + s.type + "); used for: " + s.usedFor.join(", ") + ".");
push("", "Photograph credits and licences are in " + c("refs/SOURCES.md") + ".", "");

writeFileSync(join(root, "ONTOLOGY.md"), L.join("\n"));
console.log("ONTOLOGY.md written:", L.length, "lines");
